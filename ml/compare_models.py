"""Transparent model comparison with synthetic scenario shift; NOT validated UPI fraud data.
Run from project root: python ml/compare_models.py
"""
from pathlib import Path
import json
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier,HistGradientBoostingClassifier
from sklearn.metrics import precision_score,recall_score,f1_score,average_precision_score,confusion_matrix

OUT=Path(__file__).resolve().parents[1]/'backend'/'models'/'comparison_metrics.json'
def generate(seed,n,shift=False):
    rng=np.random.default_rng(seed)
    typical=rng.uniform(200,20000,n)
    ratio=rng.lognormal(.45 if not shift else 1.1,1.2,n)
    amount=np.clip(typical*ratio,1,1_000_000)
    recent=rng.poisson(2.5 if not shift else 4.2,n).clip(0,100)
    hour=rng.integers(0,24,n)
    new=rng.binomial(1,.28 if not shift else .45,n)
    x=np.column_stack([amount,typical,recent,hour,new,amount/typical])
    # True risk outcomes are NOT observed: labels are generated by this hypothetical equation.
    logit=-3.8+1.35*(ratio>5)+1.0*new+.95*(recent>=5)+.6*(hour<5)+.4*(ratio>2)
    y=rng.binomial(1,1/(1+np.exp(-logit)))
    return x,y

train_x,train_y=generate(20261001,10000)
test_x,test_y=generate(20261002,2500)
shift_x,shift_y=generate(20261003,2500,True)
models={
    'Logistic Regression':LogisticRegression(max_iter=1200,class_weight='balanced'),
    'Random Forest':RandomForestClassifier(n_estimators=90,min_samples_leaf=15,max_depth=9,n_jobs=-1,random_state=7),
    'Histogram Gradient Boosting':HistGradientBoostingClassifier(max_iter=100,max_leaf_nodes=15,l2_regularization=1.0,random_state=7)
}
result={'description':'Independent synthetic test seeds and shifted distribution. NOT real UPI labels.','threshold':0.15,'models':{}}
for name,model in models.items():
    model.fit(train_x,train_y)
    runs={}
    for title,x,y in [('synthetic_holdout',test_x,test_y),('shifted_synthetic',shift_x,shift_y)]:
        prob=model.predict_proba(x)[:,1]
        pred=(prob>=.15).astype(int)
        runs[title]={'precision':float(precision_score(y,pred,zero_division=0)), 'recall':float(recall_score(y,pred,zero_division=0)), 'f1':float(f1_score(y,pred,zero_division=0)), 'pr_auc':float(average_precision_score(y,prob)), 'confusion_matrix':confusion_matrix(y,pred).tolist(), 'prevalence':float(y.mean())}
    result['models'][name]=runs
OUT.write_text(json.dumps(result,indent=2))
print(json.dumps(result,indent=2))
